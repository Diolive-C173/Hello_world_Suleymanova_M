# -*- coding: utf-8 -*-

# Принимаем значение pH от пользователя
ph = float(input("Введите значение pH: "))

# Определяем среду по значению pH
if ph < 0 or ph > 14:
    print("Ошибка: значение pH должно быть в диапазоне от 0 до 14")
elif ph < 7:
    print("Кислотная среда")
elif ph == 7:
    print("Нейтральная среда")
else:
    print("Щелочная среда")
