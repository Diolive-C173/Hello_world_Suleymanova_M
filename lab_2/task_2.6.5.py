#!/usr/bin/env python3
# -*- coding: utf-8 -*-

print("=" * 70)
print("              ВИТЯЗЬ НА РАСПУТЬЕ")
print("=" * 70)
print("\nПодъехал витязь к камню, а на камне написано:")
print("«Налево пойдёшь — коня потеряешь,")
print(" направо пойдёшь — себя потеряешь,")
print(" прямо пойдёшь — богатым будешь.»")
print("\n" + "-" * 70)

# Ввод выбора пути
choice = input("\nКакой путь выберешь, витязь? (налево/направо/прямо): ").strip().lower()

print("\n" + "=" * 70)
print("СУДЬБА ВИТЯЗЯ:")
print("=" * 70)

# Определение последствий выбора
if choice == "налево" or choice == "левый" or choice == "лево" or choice == "l":
    print("\nПоехал витязь налево...")
    print("-" * 70)
    print("На пути ему встретились разбойники лютые.")
    print("Битва была жестокой, но витязь оказался сильнее.")
    print("Коня его убили разбойники, но сам витязь остался жив.")
    print("\nИтог: Коня потерял, но честь сохранил.")
    print("      Отправился дальше пешим, ища справедливости.")

elif choice == "направо" or choice == "правый" or choice == "право" or choice == "r":
    print("\nПоехал витязь направо...")
    print("-" * 70)
    print("Привела его дорога к болотам топким.")
    print("Увяз в болоте витязь, и никто не пришёл на помощь.")
    print("Сгинул витязь в трясине, и память о нём исчезла.")
    print("\nИтог: Себя потерял, сгинул во тьме.")
    print("      Не стало больше витязя на земле русской.")

elif choice == "прямо" or choice == "прямой" or choice == "прям" or choice == "f" or choice == "forward":
    print("\nПоехал витязь прямо...")
    print("-" * 70)
    print("Приехал он в город богатый, где народ встречал его с почестями.")
    print("Царь предложил ему службу и награду великую.")
    print("Стал витязь воеводой, женился на царевне, жил в достатке и почёте.")
    print("\nИтог: Богатым стал, обрёл дом и семью.")
    print("      Служил верой и правдой до конца своих дней.")

else:
    print("\nНе выбрал витязь ни одного пути...")
    print("-" * 70)
    print("Стоял витязь у камня три дня и три ночи.")
    print("Так и не решившись, вернулся обратно в родные края.")
    print("\nИтог: Остался у разбитого корыта.")
    print("      Ни славы, ни богатства, ни приключений не обрёл.")